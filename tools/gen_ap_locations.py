"""
Write src/ap_locations.h from the AP world's location data: the game_key (room_key * 64 + flag) of
every placed-pickup location, sorted, for the "pickups left in this room" counter in src/pickup.c.
Run by tools/build.py before compiling, so the header follows locations.json / extra_locations.json.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'apworld' / 'lament_of_innocence' / 'data'
OUT = ROOT / 'src' / 'ap_locations.h'
BOSS_KEY_BASE = 0x8000   # src/ap.h: boss rewards, not room pickups


def generate():
    keys = set()
    for name in ('locations.json', 'extra_locations.json'):
        path = DATA / name
        if not path.exists():
            continue
        for rec in json.loads(path.read_text(encoding='utf-8')):
            key = rec.get('game_key')
            if rec.get('kind') == 'pickup' and key is not None and key < BOSS_KEY_BASE:
                keys.add(key)
    keys = sorted(keys)
    rows = [', '.join(f'{k}' for k in keys[i:i + 12]) for i in range(0, len(keys), 12)]
    text = (
        '/* Generated by tools/gen_ap_locations.py from apworld/lament_of_innocence/data; '
        'do not edit.\n'
        ' * game_key (room_key * 64 + collected-flag index) of every placed-pickup AP location, '
        'sorted. */\n'
        '#ifndef AP_LOCATIONS_H\n#define AP_LOCATIONS_H\n\n'
        f'#define AP_PICKUP_COUNT {len(keys)}\n'
        'static const unsigned short ap_pickup_keys[AP_PICKUP_COUNT] = {\n'
        + ''.join(f'    {r},\n' for r in rows)
        + '};\n\n#endif\n'
    )
    if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
        OUT.write_text(text, encoding='utf-8', newline='\n')
    return len(keys)


if __name__ == '__main__':
    print(f'{OUT}: {generate()} pickup locations')
